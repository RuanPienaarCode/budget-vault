/* Português.

   Checked against src/lang/en.js at build time — same key set, no more, no
   fewer. Add a string to en.js first, then translate it here.

   Conventions used throughout:
     - "Budget Vault" is the product name and stays untranslated. "cofre" is
       the vault, matching Obsidian's own Portuguese locale.
     - Brazilian vocabulary wherever the two standards diverge — "arquivo" not
       "ficheiro", "tela" not "ecrã", "conta corrente" not "conta à ordem".
       It is the larger readership, every one of those words is understood in
       Portugal, and the reverse is less true. Spelling follows the 1990
       orthographic agreement, which both standards share.
     - "você", and impersonal phrasing wherever a sentence carries itself
       without a pronoun — which is most of them, and reads naturally on both
       sides of the Atlantic.
     - Portuguese takes the SINGULAR at 0 as well as 1 ("0 arquivo", "1
       arquivo", "2 arquivos") — CLDR's `pt` rule — which is why 'pt' is in
       ZERO_IS_SINGULAR in i18n.js. The `one` form below therefore has to read
       correctly for zero too, so it avoids a definite article that would fix
       the number at one.
     - Date placeholders are localised: AAAA-MM-DD, not YYYY-MM-DD.
     - Day numbers arrive through i18n.day(), which renders "1º" for the first
       of the month and the bare number after that; the sentences here are
       written to sit around that ("a partir do dia 1º", "a partir do dia 25").
     - The generated report's own words are translated too — it is meant to
       leave the app and be read by someone who never sees the interface. */

